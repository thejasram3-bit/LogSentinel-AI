if torch is not None and nn is not None:
    class LogTransformer(nn.Module):
        def __init__(self, input_dim=1, d_model=32, nhead=4,
                     num_layers=2, max_len=50, dropout=0.3):
            super().__init__()
            self.input_proj = nn.Linear(input_dim, d_model)
            pe = torch.zeros(max_len, d_model)
            pos = torch.arange(0, max_len).unsqueeze(1).float()
            div = torch.exp(torch.arange(0, d_model, 2).float() *
                            -(torch.log(torch.tensor(10000.0)) / d_model))
            pe[:, 0::2] = torch.sin(pos * div)
            pe[:, 1::2] = torch.cos(pos * div)
            self.register_buffer('pe', pe.unsqueeze(0))
            encoder_layer = nn.TransformerEncoderLayer(
                d_model=d_model, nhead=nhead,
                dim_feedforward=128, dropout=dropout, batch_first=True)
            self.transformer = nn.TransformerEncoder(
                encoder_layer, num_layers=num_layers)
            self.classifier = nn.Sequential(
                nn.Linear(d_model, 16), nn.ReLU(),
                nn.Dropout(dropout), nn.Linear(16, 1), nn.Sigmoid())

        def forward(self, x):
            x = self.input_proj(x)
            x = x + self.pe
            x = self.transformer(x)
            x = x.mean(dim=1)
            return self.classifier(x).squeeze(-1)
